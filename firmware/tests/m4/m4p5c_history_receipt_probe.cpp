constexpr uint64_t kDeviceId = UINT64_C(0x1122334455667788);
constexpr uint32_t kKeyEpoch = 0x01020304U;
constexpr uint64_t kIncarnation = UINT64_C(0xA1A2A3A4A5A6A7A8);

