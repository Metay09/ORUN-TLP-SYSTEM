template <size_t Pages>
class RamFlash final : public FlashBackend {
 public:
  static constexpr size_t kSize =
      Pages * static_cast<size_t>(storage_config::kPageSize);

  bool begin() override {
    if (!initialized_) {
      memset(bytes_, 0xFF, sizeof(bytes_));
      initialized_ = true;
    }
    return true;
  }

  bool read(uint32_t offset, void* data, size_t size) const override {
    if (data == nullptr || offset > sizeof(bytes_) ||
        size > sizeof(bytes_) - offset)
      return false;
    memcpy(data, bytes_ + offset, size);
    return true;
  }

  FlashOpResult program(uint32_t offset, const void* data,
                        size_t size) override {
    if (data == nullptr || size == 0 ||
        offset > sizeof(bytes_) || size > sizeof(bytes_) - offset)
      return FlashOpResult::kFailed;

    const auto* source = static_cast<const uint8_t*>(data);
    for (size_t i = 0; i < size; ++i) {
      if ((bytes_[offset + i] & source[i]) != source[i])
        return FlashOpResult::kFailed;
    }
    for (size_t i = 0; i < size; ++i)
      bytes_[offset + i] &= source[i];
    return FlashOpResult::kDone;
  }

  FlashOpResult erasePage(uint32_t page) override {
    if (page >= Pages) return FlashOpResult::kFailed;
    memset(bytes_ + static_cast<size_t>(page) * storage_config::kPageSize,
           0xFF, storage_config::kPageSize);
    return FlashOpResult::kDone;
  }

 private:
  bool initialized_ = false;
  uint8_t bytes_[kSize]{};
};

class FixedIncarnationSource final : public HistoryIncarnationSource {
 public:
  bool generate(uint64_t& incarnation) override {
    incarnation = kIncarnation;
    return true;
  }
};

RamFlash<storage_config::kPageCount> history_flash;
RamFlash<storage_config::kFutureSecurityRegionPages> security_flash;
FixedIncarnationSource incarnation_source;
HistoryStore history_store(history_flash, &incarnation_source);
SecurityStore security_store(security_flash, security_flash);
HistorySecureCrypto crypto(security_store);
HistoryDeliveryCoordinator delivery(history_store);
HistoryReceiptAdmissionCoordinator admission(security_store, delivery);
HistoryReceiptReceiver receiver(history_store, crypto, admission);

bool settleHistory() {
  for (uint32_t guard = 0; guard < 2000U && history_store.busy(); ++guard)
    history_store.poll();
  return !history_store.busy();
}

bool settleSecurity() {
  for (uint32_t guard = 0; guard < 3000U && security_store.busy(); ++guard)
    security_store.poll();
  return !security_store.busy();
}

bool prepareHistory() {
  if (!history_store.begin(kDeviceId) || !settleHistory())
    return false;

  if (!history_store.canAppend()) {
    (void)history_store.prepareAppend();
    if (!settleHistory())
      return false;
  }

  uint32_t sequence = 0;
  uint64_t identity = 0;
  if (!history_store.nextSequence(sequence, identity) ||
      sequence != 0U || identity != 1U)
    return false;

  tlp::PositionPacket position{};
  position.source_device_id = kDeviceId;
  position.sequence_number = sequence;
  position.gnss_utc_epoch_seconds = 0x11223344U;
  position.latitude_e7 = 410000000;
  position.longitude_e7 = 290000000;
  position.altitude_mm = 1234;
  position.hdop_x100 = 150;
  position.satellites = 8;
  position.flags = tlp::kPositionFlagValidFix |
                   tlp::kPositionFlagValidUtcTime |
                   tlp::kPositionFlag3dFix;

  uint8_t packet[tlp::kPositionPacketSize]{};
  if (!tlp::serializePositionPacket(position, packet, sizeof(packet)) ||
      !history_store.append(packet, identity) ||
      !settleHistory())
    return false;

  bool append_success = false;
  return history_store.takeAppendResult(append_success) && append_success &&
         history_store.ready() &&
         history_store.incarnation() == kIncarnation &&
         history_store.count() == 1U &&
         history_store.acknowledgedThrough() == 0U &&
         history_store.deliveredThrough() == 0U;
}

bool provisionPublicCredential() {
  if (!security_store.begin(DeviceIdentity::fromLegacyUint64(kDeviceId)) ||
      security_store.state() != SecurityState::kUnprovisioned)
    return false;

  uint8_t credential_id[security_format::kCredentialIdSize]{};
  uint8_t root[security_format::kKRootSize]{};
  memcpy(credential_id, kCredentialId, sizeof(credential_id));
  memcpy(root, kRoot, sizeof(root));

  if (!security_store.commitCredential(
          credential_id, kKeyEpoch, root) ||
      !settleSecurity())
    return false;

  bool commit_success = false;
  if (!security_store.takeCommitResult(commit_success) || !commit_success)
    return false;

  if (!settleSecurity())
    return false;

  return security_store.ready() &&
         security_store.state() == SecurityState::kProvisioned &&
         security_store.currentKeyEpoch() == kKeyEpoch;
}

