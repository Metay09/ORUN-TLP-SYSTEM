HistoryReceiptKatResult runHistoryReceiptKat() {
  HistoryReceiptKatResult result{};

  result.history_ready = prepareHistory();
  result.provision = provisionPublicCredential();
  if (!result.history_ready || !result.provision)
    return result;

  const auto started =
      receiver.submitBackendDurableFrame(kReceiptFrame, sizeof(kReceiptFrame));
  result.opaque_started =
      started == HistoryReceiptReceiver::SubmitResult::kStarted &&
      receiver.pending() && security_store.busy() &&
      history_store.acknowledgedThrough() == 0U;

  if (!result.opaque_started)
    return result;

  // The pending M4P5B owner must reject a second raw frame before another
  // crypto/open or SecurityStore replay-result owner can overtake it.
  result.busy_guard =
      receiver.submitBackendDurableFrame(kReceiptFrame,
                                         sizeof(kReceiptFrame)) ==
          HistoryReceiptReceiver::SubmitResult::kBusy &&
      receiver.pending();

  result.replay_wait =
      receiver.service() ==
          HistoryReceiptAdmissionCoordinator::ServiceResult::kWaitingReplay &&
      history_store.acknowledgedThrough() == 0U;

  if (!result.busy_guard || !result.replay_wait || !settleSecurity())
    return result;

  result.applied =
      receiver.service() ==
          HistoryReceiptAdmissionCoordinator::ServiceResult::kApplied &&
      !receiver.pending() &&
      history_store.acknowledgedThrough() == 1U &&
      history_store.deliveredThrough() == 0U;

  if (!result.applied)
    return result;

  uint8_t tampered[sizeof(kReceiptFrame)]{};
  memcpy(tampered, kReceiptFrame, sizeof(tampered));
  tampered[sizeof(tampered) - 1U] ^= 0x01U;

  result.tamper_rejected =
      receiver.submitBackendDurableFrame(tampered, sizeof(tampered)) ==
          HistoryReceiptReceiver::SubmitResult::kAuthRejected &&
      !receiver.pending() &&
      history_store.acknowledgedThrough() == 1U;

  // The original valid frame authenticates again but its already-consumed A2D
  // counter must be rejected by SecurityStore before any second History effect.
  const auto duplicate =
      receiver.submitBackendDurableFrame(kReceiptFrame, sizeof(kReceiptFrame));
  result.duplicate_rejected =
      duplicate == HistoryReceiptReceiver::SubmitResult::kStarted &&
      receiver.service() ==
          HistoryReceiptAdmissionCoordinator::ServiceResult::kReplayRejected &&
      !receiver.pending() &&
      history_store.acknowledgedThrough() == 1U &&
      history_store.deliveredThrough() == 0U;

  return result;
}

