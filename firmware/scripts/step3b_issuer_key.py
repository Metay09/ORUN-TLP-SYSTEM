"""Step 3B: pin the Gateway issuer PUBLIC key into the bench Gateway image.

Reads the owner's issuer public key (64 hex chars, written by
`python3 tools/orun_provision.py issuer`) from $ORUN_ISSUER_PUBLIC_KEY_FILE
or ~/orun-issuer.pub and generates `orun_step3b_issuer_key.h` in the build
directory. The private key never leaves the backend registry.

No key file -> the build STOPS with the command that creates it. Set
ORUN_STEP3B_ALLOW_NO_ISSUER=1 to build anyway with ORUN_STEP3B_ISSUER_PINNED 0:
that image accepts NO signed grant snapshot (BENCH? shows NO_ISSUER_KEY).
The key is never taken from USB, BLE or radio at run time.
"""
import os
import re
from pathlib import Path

Import("env")  # noqa: F821  (PlatformIO/SCons)

path = Path(os.environ.get("ORUN_ISSUER_PUBLIC_KEY_FILE",
                           str(Path.home() / "orun-issuer.pub"))).expanduser()
out_dir = Path(env.subst("$BUILD_DIR")) / "step3b_generated"  # noqa: F821
out_dir.mkdir(parents=True, exist_ok=True)
header = out_dir / "orun_step3b_issuer_key.h"

key = None
if path.is_file():
    text = re.sub(r"\s+", "", path.read_text()).upper()
    if not re.fullmatch(r"[0-9A-F]{64}", text):
        raise SystemExit(f"step3b: {path} is not a 32-byte hex Ed25519 public key")
    raw = bytes.fromhex(text)
    if raw in (bytes(32), b"\xff" * 32):
        raise SystemExit(f"step3b: {path} holds an unusable key")
    key = raw

lines = ["// Generated by firmware/scripts/step3b_issuer_key.py. Do not edit.",
         "#pragma once"]
if key is None:
    if os.environ.get("ORUN_STEP3B_ALLOW_NO_ISSUER") != "1":
        raise SystemExit(
            f"step3b: issuer public key {path} not found. Create it first:\n"
            "    python3 tools/orun_provision.py issuer\n"
            "(or set ORUN_STEP3B_ALLOW_NO_ISSUER=1 for an image without signed grants)")
    print(f"step3b: NO issuer key ({path} missing): signed Gateway grants disabled")
    lines.append("#define ORUN_STEP3B_ISSUER_PINNED 0")
else:
    print(f"step3b: issuer public key pinned from {path} (starts {key[:4].hex().upper()})")
    lines.append("#define ORUN_STEP3B_ISSUER_PINNED 1")
    lines.append("#define ORUN_STEP3B_ISSUER_PUBLIC_KEY { " +
                 ", ".join(f"0x{b:02X}" for b in key) + " }")
content = "\n".join(lines) + "\n"
if not header.exists() or header.read_text() != content:
    header.write_text(content)
env.Append(CPPPATH=[str(out_dir)])  # noqa: F821
