#!/usr/bin/env python3
"""Wrap one Nordic nRF52 *application-only* DFU ZIP for ORUN Android.

The input is a DFU package generated by the existing firmware toolchain, not
an arbitrary .bin. This tool does not compile firmware or talk to a device.
The init packet is retained verbatim: only the bootloader may validate it.

    python3 tools/orun_telefon_paketi.py /path/to/firmware.zip --out orun.zip
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo, BadZipFile

MAX_ARCHIVE = 2 * 1024 * 1024
MAX_APP = 900 * 1024
MAX_DAT = 64 * 1024
MAX_ENTRIES = 16
SOURCE_SHA = re.compile(r"[0-9a-fA-F]{40}\Z")


class PackageError(ValueError):
    """Bad or unsupported DFU input; never produces a firmware package."""


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _safe_name(name: str) -> bool:
    return bool(name and not name.startswith(("/", "\\")) and
                "\\" not in name and all(p not in ("", ".", "..") for p in name.split("/")))


def read_dfu(path: Path) -> tuple[bytes, bytes, str]:
    """Read exactly one application + init packet from a Nordic DFU archive."""
    if not path.is_file() or path.stat().st_size > MAX_ARCHIVE:
        raise PackageError("Nordic DFU ZIP yok veya beklenenden büyük.")
    try:
        with ZipFile(path) as z:
            entries = z.infolist()
            if not 1 <= len(entries) <= MAX_ENTRIES:
                raise PackageError("DFU ZIP içindeki dosya sayısı geçersiz.")
            names = [i.filename for i in entries]
            if len(names) != len(set(names)) or any(not _safe_name(n) for n in names):
                raise PackageError("DFU ZIP içinde güvensiz veya tekrarlanan yol var.")
            if any(i.is_dir() or i.flag_bits & 1 or i.file_size > MAX_APP for i in entries):
                raise PackageError("DFU ZIP dizin, şifreli veya çok büyük dosya içeriyor.")
            if "manifest.json" not in names:
                raise PackageError("Nordic DFU manifest.json bulunamadı.")
            manifest_file = z.getinfo("manifest.json")
            if manifest_file.file_size > 16 * 1024:
                raise PackageError("Nordic DFU manifesti çok büyük.")
            try:
                manifest = json.loads(z.read("manifest.json"))
            except (ValueError, UnicodeError) as e:
                raise PackageError("Nordic DFU manifesti okunamıyor.") from e
            sections = manifest.get("manifest") if isinstance(manifest, dict) else None
            if not isinstance(sections, dict) or set(sections) != {"application"}:
                raise PackageError("Yalnız uygulama imajı kabul edilir; bootloader/SoftDevice yüklenmez.")
            app = sections["application"]
            if not isinstance(app, dict):
                raise PackageError("Uygulama manifesti geçersiz.")
            bin_name, dat_name = app.get("bin_file"), app.get("dat_file")
            if not isinstance(bin_name, str) or not isinstance(dat_name, str) or bin_name == dat_name:
                raise PackageError("Uygulamanın .bin ve .dat dosyaları belirtilmemiş.")
            if not bin_name.endswith(".bin") or not dat_name.endswith(".dat"):
                raise PackageError("DFU imaj ve init uzantıları beklenmedik.")
            if set(names) != {"manifest.json", bin_name, dat_name}:
                raise PackageError("DFU ZIP içinde beklenmeyen dosyalar var.")
            if z.getinfo(bin_name).file_size > MAX_APP or z.getinfo(dat_name).file_size > MAX_DAT:
                raise PackageError("Uygulama veya init paketi boyut sınırını aşıyor.")
            image, init = z.read(bin_name), z.read(dat_name)
            if not (0 < len(image) <= MAX_APP and 0 < len(init) <= MAX_DAT):
                raise PackageError("Boş veya fazla büyük DFU imajı/init paketi.")
            return image, init, _sha(path.read_bytes())
    except (BadZipFile, OSError, RuntimeError) as e:
        raise PackageError("Nordic DFU ZIP okunamadı veya bozuk.") from e


def package_dfu(src: Path, dest: Path, commit: str) -> dict:
    if not SOURCE_SHA.fullmatch(commit):
        raise PackageError("Kaynak commit tam 40 haneli Git SHA olmalı.")
    if src.resolve() == dest.resolve():
        raise PackageError("Giriş ve çıkış dosyası aynı olamaz.")
    image, init, source_hash = read_dfu(src)
    meta = {
        "format": "orun-serial-dfu", "version": 1,
        "target": {"board": "RAK4630", "chip": "nRF52840", "env": "rak4630_orun"},
        "source_commit": commit.lower(), "source_dfu_sha256": source_hash,
        "application": {
            "bin": "application.bin", "bin_sha256": _sha(image), "bin_size": len(image),
            "dat": "application.dat", "dat_sha256": _sha(init), "dat_size": len(init),
        },
    }
    if dest.exists():
        raise PackageError("Çıktı zaten var, üzerine yazılmadı.")
    dest.parent.mkdir(parents=True, exist_ok=True)
    try:
        with ZipFile(dest, "x", compression=ZIP_DEFLATED, compresslevel=9) as out:
            for name, data in (
                ("orun-package.json", (json.dumps(meta, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode()),
                ("application.bin", image), ("application.dat", init),
            ):
                zi = ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
                zi.compress_type = ZIP_DEFLATED
                zi.external_attr = 0o600 << 16
                out.writestr(zi, data, compress_type=ZIP_DEFLATED, compresslevel=9)
    except Exception:
        dest.unlink(missing_ok=True)
        raise
    return meta


def _commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], stderr=subprocess.DEVNULL,
                                       text=True).strip()
    except (OSError, subprocess.CalledProcessError) as e:
        raise PackageError("Git sürümü okunamadı, --source-commit ile belirt.") from e


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Nordic DFU ZIP -> telefona kopyalanacak orun.zip (cihaza yazmaz)")
    p.add_argument("dfu_zip", type=Path, help="Var olan, yalnız uygulama içeren Nordic DFU ZIP")
    p.add_argument("--out", required=True, type=Path, help="Oluşturulacak ORUN ZIP yolu (varsa üzerine yazılmaz)")
    p.add_argument("--source-commit", default=None, help="Yazılımı üreten tam Git commit SHA")
    args = p.parse_args(argv)
    try:
        meta = package_dfu(args.dfu_zip, args.out, args.source_commit or _commit())
    except PackageError as e:
        print("DUR:", e, file=sys.stderr)
        return 2
    print(f"ORUN paketi oluşturuldu: {args.out} | uygulama {meta['application']['bin_size']} bayt")
    print("Bu yalnız paketlemedir: cihaza yazılım yüklenmedi; Android/RAK doğrulaması yapılmadı.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
