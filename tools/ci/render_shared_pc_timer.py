#!/usr/bin/env python3
"""Create *uninstalled* ORUN PC Edge mirror systemd user unit candidates.

This command NEVER calls systemctl, installs a unit, restarts a service,
writes a live PC Edge database or reads a token's content. Keep generated
units in a private staging directory until owner approves real deployment.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import stat
import sys

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from tools.orun_shared_pc_mirror import ID, validate_origin

UNIT = "orun-shared-pc-mirror.service"
TIMER = "orun-shared-pc-mirror.timer"
SAFE_ARG = re.compile(r"^[A-Za-z0-9_./:+-]+$")


def _simple(value: str) -> str:
    """No shell or systemd interpolation in synthesized ExecStart."""
    if not value or not SAFE_ARG.fullmatch(value) or "%" in value or "$" in value:
        raise ValueError("invalid systemd parameter")
    return value


def _absolute(value: str) -> str:
    path = Path(value)
    if not path.is_absolute():
        raise ValueError("absolute path required")
    return _simple(str(path))


def render(repo: Path, output_dir: Path, db: Path, site: str,
           installation: str, origin: str, token_file: Path,
           interpreter: Path = Path(sys.executable)) -> tuple[Path, Path]:
    if not isinstance(site, str) or not ID.fullmatch(site) or (
            not isinstance(installation, str) or not ID.fullmatch(installation)):
        raise ValueError("invalid site or installation")
    origin = _simple(validate_origin(origin))
    repo, output_dir, db, token_file = (
        Path(repo), Path(output_dir), Path(db), Path(token_file))
    entrypoint = repo / "tools" / "orun_shared_pc_mirror.py"
    if not entrypoint.is_file():
        raise ValueError("repository entrypoint not found")
    if not output_dir.is_dir() or output_dir.is_symlink():
        raise ValueError("staging output dir missing or symlink")
    # Never write directly into live unit directories. Installation must
    # remain a separate, reviewed and explicitly owner-initiated operation.
    if (str(output_dir.resolve()).startswith("/etc/systemd/") or
            output_dir.resolve() == Path.home() / ".config/systemd/user"):
        raise ValueError("direct systemd unit installation forbidden")
    if not db.parent.is_dir() or db == token_file or not token_file.is_file():
        raise ValueError("DB parent and existing token file required")
    st = token_file.lstat()
    if (not stat.S_ISREG(st.st_mode) or stat.S_IMODE(st.st_mode) & 0o077 or
            st.st_uid != os.geteuid()):
        raise ValueError("token file must be private 0600, owned by current user")
    args = [
        _absolute(str(interpreter)), _absolute(str(entrypoint)),
        "--db", _absolute(str(db)), "--site", _simple(site),
        "--installation", _simple(installation),
        "--url", origin, "--token-file", _absolute(str(token_file)), "--once",
    ]
    service = """# ORUN candidate generated by render_shared_pc_timer.py; NOT INSTALLED
[Unit]
Description=ORUN PC Edge shared-data mirror (read-only, separate from observations)
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
UMask=0077
NoNewPrivileges=true
PrivateTmp=true
ExecStart={command}
""".format(command=" ".join(args))
    timer = """# ORUN candidate generated by render_shared_pc_timer.py; NOT INSTALLED
[Unit]
Description=ORUN PC Edge read-only shared-data sync schedule

[Timer]
OnBootSec=60s
OnUnitInactiveSec=180s
RandomizedDelaySec=30s
Persistent=false
Unit=orun-shared-pc-mirror.service

[Install]
WantedBy=timers.target
"""
    targets = [output_dir / UNIT, output_dir / TIMER]
    if any(p.exists() or p.is_symlink() for p in targets):
        raise FileExistsError("staging unit already exists; nothing overwritten")
    created = []
    try:
        for path, content in zip(targets, (service, timer)):
            fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL |
                         getattr(os, "O_NOFOLLOW", 0), 0o600)
            created.append(path)
            with os.fdopen(fd, "w", encoding="utf-8") as f:
                f.write(content)
    except BaseException:
        for path in created:
            path.unlink(missing_ok=True)
        raise
    return targets[0], targets[1]


def main() -> int:
    p = argparse.ArgumentParser(description="Render disabled PC mirror units to private staging")
    p.add_argument("--repo", default=str(ROOT))
    p.add_argument("--output-dir", required=True)
    p.add_argument("--db", required=True)
    p.add_argument("--site", required=True)
    p.add_argument("--installation", required=True)
    p.add_argument("--url", required=True)
    p.add_argument("--token-file", required=True)
    opts = p.parse_args()
    try:
        service, timer = render(Path(opts.repo), Path(opts.output_dir),
                                Path(opts.db), opts.site, opts.installation,
                                opts.url, Path(opts.token_file))
    except (ValueError, FileExistsError, OSError) as exc:
        print("ORUN_UNIT_RENDER_FAILED:", type(exc).__name__, file=sys.stderr)
        return 1
    print("ORUN_DISABLED_SERVICE_PREPARED:", service)
    print("ORUN_DISABLED_TIMER_PREPARED:", timer)
    print("NO_SYSTEMD_CHANGES; NO_SERVICE_START; NO_LIVE_DB_CHANGE")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
